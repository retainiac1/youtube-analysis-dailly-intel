// Interpretation page: the generation home. A controls panel (model + temperature
// + seed, a Run button, and a stopwatch) sits above the interpretation card; the
// card below shows the stored summary for the current run + lane (the same
// read-only path the Trends rail uses). Run triggers POST /api/interpret for the
// viewed lane and renders the returned summary; on an empty lane it shows a clean
// skip state, and on a provider error it shows the message inline (never a 500).
//
// Per-model capability (which params a model honors) is reported by the server and
// drives the grey-out, so a control is never live for a parameter the model would
// silently ignore. The client never hardcodes provider rules.

import * as api from "./api.js";

let el = null;            // the page mount (<main id="interpretation">)
let resultEl = null;      // where the stored/generated summary renders
let controls = null;      // { modelSelect, tempInput, seedInput, thinkInput, thinkControl, runBtn, errorEl, stopwatchEl }
let caps = {};            // { "provider:model": { temperature, seed, reasoning, think } }
let defaultTemperature = 1.0;
let currentState = { runDate: null, lane: "health" };
let buildPromise = null;  // ensures the scaffold (and one defaults fetch) is built once

export function init(mount) {
  el = mount;
}

// Build a DOM node with text assigned via textContent ONLY. The interpretation is
// LLM-generated text, so it is never inserted as HTML (no innerHTML, no markdown
// parsing): textContent + CSS white-space: pre-wrap keeps it safe, true prose.
function node(tag, opts = {}, children = []) {
  const n = document.createElement(tag);
  if (opts.class) n.className = opts.class;
  if (opts.text != null) n.textContent = opts.text;
  if (opts.type != null) n.type = opts.type;
  if (opts.attrs) for (const [k, v] of Object.entries(opts.attrs)) n.setAttribute(k, v);
  for (const c of children) n.appendChild(c);
  return n;
}

// --- result region (stored read path + post-run render) ---------------------

function renderEmpty(message) {
  resultEl.replaceChildren(
    node("div", { class: "empty-state" }, [
      node("p", { class: "heading-sm", text: "No interpretation yet" }),
      node("p", { text: message }),
    ])
  );
}

function renderError(message) {
  resultEl.replaceChildren(
    node("div", { class: "empty-state empty-error" }, [
      node("p", { class: "heading-sm", text: "Could not load the interpretation." }),
      node("p", { text: message }),
    ])
  );
}

// Milliseconds -> a compact "3.2s", or null when there is no measured duration
// (so the meta line omits it). Shared by the live stopwatch and the stored value.
function formatDuration(ms) {
  if (ms == null || Number.isNaN(ms)) return null;
  return `${(ms / 1000).toFixed(1)}s`;
}

// Understated "AI-generated, how long, and when" line. generated_at is an Eastern
// ISO-8601 string; show a light, readable form and fall back to the raw value if
// it does not parse. Tolerates a missing date (the just-generated card has no
// timestamp until the next read) and a missing duration (un-instrumented rows).
function metaLine(model, generatedAt, durationMs) {
  const parts = [];
  if (model) parts.push(`Generated by ${model}`);
  const dur = formatDuration(durationMs);
  if (dur) parts.push(`took ${dur}`);
  if (generatedAt) {
    const d = new Date(generatedAt);
    parts.push(isNaN(d) ? generatedAt : d.toLocaleString());
  }
  return parts.join(" · ");
}

// The applied generation parameters for this run: temperature, seed, and think,
// each rendered as not-applicable ("n/a") when NULL — temperature/seed NULL on a
// model that ignored them, think NULL when the model is not reasoning-capable or
// its provider does not honor the toggle, "off"/"on" when it does. Returns "" when
// the row carries no provenance keys at all (an older payload), so the line is
// omitted rather than showing three "n/a"s.
function paramsLine(data) {
  if (data.temperature === undefined && data.seed === undefined
      && data.think === undefined) {
    return "";
  }
  const na = "n/a";
  const temp = data.temperature == null ? na : String(data.temperature);
  const seed = data.seed == null ? na : String(data.seed);
  const think = data.think == null ? na : (data.think ? "on" : "off");
  return `temperature ${temp} · seed ${seed} · think ${think}`;
}

function renderCard(data) {
  const card = node("section", { class: "glass-panel interpretation-card" }, [
    node("h2", { class: "heading-sm", text: "Interpretation" }),
  ]);
  const meta = metaLine(data.model, data.generated_at, data.duration_ms);
  if (meta) card.appendChild(node("p", { class: "interpretation-meta", text: meta }));
  const params = paramsLine(data);
  if (params) card.appendChild(node("p", { class: "interpretation-params", text: params }));
  card.appendChild(node("div", { class: "interpretation-text", text: data.text }));
  // The thinking transcript, when think was on. It is transient (returned only on
  // the fresh /api/interpret response, never persisted), so it appears right after a
  // think-on generation and is absent on a re-read. Collapsed by default; the larger
  // token count it implies is intended, not a bug. textContent only — never HTML.
  if (data.thinking) {
    card.appendChild(node("details", { class: "interpretation-thinking" }, [
      node("summary", { text: "Thinking" }),
      node("div", { class: "interpretation-thinking-text", text: data.thinking }),
    ]));
  }
  resultEl.replaceChildren(card);
}

// --- controls scaffold ------------------------------------------------------

function labeled(text, input) {
  return node("label", { class: "control-label interpret-control" }, [
    node("span", { text }),
    input,
  ]);
}

// Grey (disable) the controls the selected model would silently ignore, per the
// server-reported capability map. NO provider hardcode: a model's honored params
// come from caps[model], the single source the adapter also derives from.
//
// The think toggle has TWO gates: `reasoning` SHOWS it (the model can think) and
// `think` ENABLES it (this provider's adapter actually honors the toggle). A
// reasoning model on a non-honoring provider shows a disabled, forced-OFF toggle —
// the honest no-op, not a hidden one. A non-reasoning model hides the toggle.
function applyCapabilities(model) {
  const c = caps[model] || { temperature: true, seed: true, reasoning: false, think: false };
  const { tempInput, seedInput, thinkInput, thinkControl } = controls;
  tempInput.disabled = !c.temperature;
  seedInput.disabled = !c.seed;
  tempInput.closest(".interpret-control").classList.toggle("control-muted", !c.temperature);
  seedInput.closest(".interpret-control").classList.toggle("control-muted", !c.seed);
  tempInput.title = c.temperature ? "" : "This model ignores temperature";
  seedInput.title = c.seed ? "" : "This model ignores seed";

  thinkControl.hidden = !c.reasoning;
  const honored = !!c.think;
  thinkInput.disabled = !honored;
  if (!honored) thinkInput.checked = false;   // force the off state when not honored
  thinkControl.classList.toggle("control-muted", c.reasoning && !honored);
  thinkInput.title = honored
    ? ""
    : "This model reasons internally; thinking output is not exposed";
}

async function buildScaffold() {
  const modelSelect = node("select", { class: "interpret-select", attrs: { "aria-label": "Model" } });
  const tempInput = node("input", { type: "number", attrs: { step: "0.1", min: "0", max: "2", "aria-label": "Temperature" } });
  const seedInput = node("input", { type: "number", attrs: { step: "1", min: "1", "aria-label": "Seed" } });
  // Think toggle: a checkbox under a "Think" caption. The checkbox is wrapped (not a
  // direct child of .interpret-control) so the `> input` text-input styling for
  // temperature/seed never applies to it. Shown/enabled by applyCapabilities.
  const thinkInput = node("input", { type: "checkbox", attrs: { "aria-label": "Think" } });
  const thinkControl = node("div", { class: "interpret-control interpret-think" }, [
    node("span", { class: "control-label", text: "Think" }),
    node("div", { class: "interpret-think-box" }, [thinkInput]),
  ]);
  const runBtn = node("button", { class: "btn-primary interpret-run", type: "button", text: "Run" });
  // Run-time element: a labeled value with a visible resting state ("—") so it is
  // never an invisible empty span. Ticks live during a run, then freezes to the
  // server's authoritative duration.
  const stopwatchEl = node("span", { class: "interpret-stopwatch", text: "—", attrs: { "aria-live": "polite" } });
  // Compact inline readout (caption + value on one line), bundled with the Run button
  // below so the pair stays adjacent and never orphans onto its own wrapped row.
  const runtime = node("div", { class: "interpret-runtime" }, [
    node("span", { class: "control-label", text: "Run time" }),
    stopwatchEl,
  ]);
  const errorEl = node("p", { class: "interpret-error", attrs: { role: "alert" } });

  // Prompt-fields multi-select: a button that toggles a checkbox panel. The
  // options + the pre-checked selection come from the server (one source of truth);
  // the selection persists server-side, so a reload re-checks the same boxes.
  // Styled to match the Model <select> box (.interpret-select); shows an "N
  // selected" summary and opens the checkbox menu.
  const fieldsToggle = node("button", {
    class: "interpret-select fields-toggle", type: "button", text: "Prompt Columns",
    attrs: { "aria-expanded": "false", "aria-haspopup": "true" },
  });
  const fieldsPanel = node("div", {
    class: "fields-panel", attrs: { role: "group", "aria-label": "Prompt columns" },
  });
  fieldsPanel.hidden = true;
  const fieldsDropdown = node("div", { class: "fields-dropdown" }, [fieldsToggle, fieldsPanel]);
  const fieldsControl = node("div", { class: "interpret-control" }, [
    node("span", { class: "control-label", text: "Prompt Columns" }),
    fieldsDropdown,
  ]);

  controls = { modelSelect, tempInput, seedInput, thinkInput, thinkControl, runBtn,
               errorEl, stopwatchEl, fieldsToggle, fieldsPanel, fieldsDropdown };

  // Run + run-time travel together as one flex item so they wrap as a unit.
  const runGroup = node("div", { class: "interpret-run-group" }, [runBtn, runtime]);

  const panel = node("section", { class: "glass-panel interpret-controls" }, [
    node("h2", { class: "heading-sm", text: "Generate interpretation" }),
    node("div", { class: "interpret-controls-row" }, [
      labeled("Model", modelSelect),
      labeled("Temperature", tempInput),
      labeled("Seed", seedInput),
      thinkControl,
      fieldsControl,
      runGroup,
    ]),
    errorEl,
  ]);

  resultEl = node("div", { class: "interpret-result" });
  el.replaceChildren(panel, resultEl);

  runBtn.addEventListener("click", onRun);
  modelSelect.addEventListener("change", () => applyCapabilities(modelSelect.value));

  // Fields dropdown wiring: toggle open/closed, keep the count label fresh, and
  // close on an outside click.
  fieldsToggle.addEventListener("click", () => {
    const open = fieldsPanel.hidden;
    fieldsPanel.hidden = !open;
    fieldsToggle.setAttribute("aria-expanded", open ? "true" : "false");
  });
  fieldsPanel.addEventListener("change", updateFieldsLabel);
  document.addEventListener("click", (e) => {
    if (!fieldsPanel.hidden && !fieldsDropdown.contains(e.target)) {
      fieldsPanel.hidden = true;
      fieldsToggle.setAttribute("aria-expanded", "false");
    }
  });

  // One defaults fetch populates the model dropdown, capability map, last-used
  // model/temperature/seed, AND the field options + persisted selection. A failure
  // leaves Run disabled with an inline message, but the read path below still shows
  // any stored interpretation.
  try {
    const d = await api.getInterpretDefaults();
    caps = d.capabilities || {};
    defaultTemperature = d.temperature != null ? d.temperature : 1.0;
    for (const m of d.models || []) {
      modelSelect.appendChild(node("option", { text: m, attrs: { value: m } }));
    }
    if (d.model) modelSelect.value = d.model;
    tempInput.value = d.temperature != null ? d.temperature : "";
    seedInput.value = d.seed != null ? d.seed : "";
    applyCapabilities(modelSelect.value);
    buildFieldOptions(d.available_fields || [], d.selected_fields || []);
    if (!(d.models && d.models.length)) {
      runBtn.disabled = true;
      errorEl.textContent = "No models are configured.";
    }
  } catch (err) {
    runBtn.disabled = true;
    errorEl.textContent = `Could not load model options: ${err.message || err}`;
  }
}

// Render one checkbox per available field, pre-checking the persisted selection,
// then refresh the toggle's "(N)" count.
function buildFieldOptions(available, selected) {
  const set = new Set(selected);
  const labels = available.map((f) => {
    const cb = node("input", { type: "checkbox", attrs: { value: f.key } });
    cb.checked = set.has(f.key);
    return node("label", { class: "fields-option" }, [cb, node("span", { text: f.label })]);
  });
  controls.fieldsPanel.replaceChildren(...labels);
  updateFieldsLabel();
}

function selectedFields() {
  return [...controls.fieldsPanel.querySelectorAll("input:checked")].map((i) => i.value);
}

function updateFieldsLabel() {
  controls.fieldsToggle.textContent = `${selectedFields().length} selected`;
}

function ensureBuilt() {
  if (!buildPromise) buildPromise = buildScaffold();
  return buildPromise;
}

// --- run handler ------------------------------------------------------------

function readParams() {
  let temperature = Number(controls.tempInput.value);
  if (Number.isNaN(temperature)) temperature = defaultTemperature;
  const raw = controls.seedInput.value;
  let seed = raw === "" ? null : Number(raw);
  if (seed != null && Number.isNaN(seed)) seed = null;
  // think: a real on/off only when the toggle is interactive (an honoring model).
  // Disabled/hidden -> null ("not applicable"); the server normalizes either way,
  // and null persists as NULL while false persists as 0 (the honored-off case).
  const think = controls.thinkInput.disabled ? null : controls.thinkInput.checked;
  return { model: controls.modelSelect.value, temperature, seed, think };
}

async function onRun() {
  if (!currentState.runDate) {
    controls.errorEl.textContent = "Select a run first.";
    return;
  }
  const { model, temperature, seed, think } = readParams();
  const { runBtn, errorEl, stopwatchEl } = controls;
  errorEl.textContent = "";
  runBtn.disabled = true;

  const start = performance.now();
  const tick = () => {
    stopwatchEl.textContent = formatDuration(performance.now() - start);
  };
  tick();
  const timer = setInterval(tick, 100);

  try {
    const res = await api.runInterpret({
      runDate: currentState.runDate,
      scope: currentState.lane,
      model,
      temperature,
      seed,
      think,
      fields: selectedFields(),
      // Generate for the SELECTED window (the shared date filter), not just the active
      // run: the producers aggregate over [startDate, endDate] and the row is keyed by
      // that window. context_mode is added by Gate C (defaults to aggregated server-side).
      startDate: currentState.startDate,
      endDate: currentState.endDate,
    });
    clearInterval(timer);
    // Branch on skipped FIRST: an empty lane wrote nothing, so show the skip state
    // and never a card/meta (or a run time) for a summary that does not exist.
    if (res.skipped) {
      stopwatchEl.textContent = "—";
      renderEmpty("Nothing to summarize: this lane has no ranked videos for the selected run.");
    } else {
      // Freeze to the SERVER's measured generate() time — the value that is also
      // stored — rather than the client round-trip, so live and persisted agree.
      stopwatchEl.textContent = formatDuration(res.duration_ms) || "—";
      // Map the applied provenance into the same keys the stored read path uses:
      // temperature is the requested value (what synthesize_lane persists), seed/
      // think are the APPLIED values, and `thinking` is the transient reasoning
      // content (present only on this fresh response, never re-fetched).
      renderCard({
        text: res.text, model: res.model, duration_ms: res.duration_ms,
        temperature, seed: res.seed_applied, think: res.think_applied,
        thinking: res.thinking,
      });
      // A written run logged a new invocation, so the spend totals changed. Notify
      // the spend panel (main.js routes this to the Interpretation panel's refresh).
      // Only the written branch: a skipped lane logs nothing, so spend is unchanged.
      document.dispatchEvent(new CustomEvent("interpretation:generated"));
    }
  } catch (err) {
    clearInterval(timer);
    tick(); // freeze the elapsed at the moment of failure
    errorEl.textContent = err.message || String(err);
  } finally {
    runBtn.disabled = false;
  }
}

// --- entry / refresh --------------------------------------------------------

export async function refresh(state) {
  currentState = state;
  await ensureBuilt();

  if (!state.runDate) {
    renderEmpty("The interpretation fills in once the pipeline records a run.");
    return;
  }
  let data;
  try {
    data = await api.getInterpretation(state.lane, state.startDate, state.endDate);
  } catch (err) {
    renderError(String(err.message || err));
    return;
  }
  // Absent row: endpoint returns 200 with empty text. Treat as empty, not failure.
  if (!data.text || !data.text.trim()) {
    renderEmpty("No interpretation has been generated for this run yet. Pick a model and click Run.");
    return;
  }
  renderCard(data);
}
