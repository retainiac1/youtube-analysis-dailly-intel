// Read-only interpretation rail. Shows the stored LLM summary for the current lane +
// window beside the charts, so the prose and the evidence sit together. Display only: it
// reuses api.getInterpretation (the same data path as the /interpretation page) and has no
// controls and no write path. The single way out is the "Tune" link, which routes to
// /interpretation for generation. The structured contract JSON is rendered by the shared
// interp-render module (the same readable per-section body the page card uses).
//
// A FACTORY (create(mount) -> {refresh}): the Trends page and the Dashboard each mount their
// own instance, so it cannot be a module singleton. Each instance owns its element and a
// latest-wins sequence token, so a slow fetch for an old window never overwrites a newer one.

import * as api from "./api.js";
import { navigate } from "./router.js";
import { loadSpec, renderInterpretationBody } from "./interp-render.js";

const INTERPRETATION_ROUTE = "/interpretation";

function node(tag, opts = {}, children = []) {
  const n = document.createElement(tag);
  if (opts.class) n.className = opts.class;
  if (opts.text != null) n.textContent = opts.text;
  if (opts.href != null) n.setAttribute("href", opts.href);
  for (const c of children) if (c) n.appendChild(c);
  return n;
}

// The "Tune" link. Created dynamically, so the router does not auto-wire it: intercept the
// plain left-click and navigate(); modified/middle clicks fall through so cmd/ctrl/middle
// still opens /interpretation in a new tab. Keyboard Enter fires a plain click, so it works.
function tuneLink() {
  const a = node("a", { class: "rail-tune", href: INTERPRETATION_ROUTE, text: "Tune this interpretation" });
  a.addEventListener("click", (e) => {
    if (e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    e.preventDefault();
    navigate(INTERPRETATION_ROUTE);
  });
  return a;
}

function formatDuration(ms) {
  if (ms == null || Number.isNaN(ms)) return null;
  return `${(ms / 1000).toFixed(1)}s`;
}

// Understated "AI-generated, how long, and when" line. generated_at is an Eastern ISO-8601
// string; show a readable form and fall back to the raw value if it does not parse.
function metaLine(model, generatedAt, durationMs) {
  const parts = [];
  if (model) parts.push(`Generated by ${model}`);
  const dur = formatDuration(durationMs);
  if (dur) parts.push(`took ${dur}`);
  if (generatedAt) {
    const d = new Date(generatedAt);
    parts.push(isNaN(d) ? generatedAt : d.toLocaleString());
  }
  return parts.join(" · ");
}

// Title names the lane and run so it is clear what the text describes, e.g.
// "Interpretation, health, 2026-06-09".
function titleFor(lane, runDate) {
  return `Interpretation, ${lane}, ${runDate}`;
}

export function create(mount) {
  const el = mount;
  let seq = 0;   // latest-wins: a response whose token is not the newest is dropped

  function renderTitleThen(lane, runDate, ...rest) {
    el.replaceChildren(
      node("h2", { class: "heading-sm rail-title", text: titleFor(lane, runDate) }),
      ...rest,
    );
  }

  function renderLoading(lane, runDate) {
    renderTitleThen(lane, runDate,
      node("div", { class: "rail-empty" }, [node("p", { text: "Loading interpretation..." })]));
  }

  function renderEmpty(lane, runDate) {
    renderTitleThen(lane, runDate,
      node("div", { class: "rail-empty" }, [node("p", { text: "No interpretation for this period yet. Generate one on the Interpretation page." })]),
      tuneLink());
  }

  function renderError(message) {
    el.replaceChildren(
      node("div", { class: "rail-empty empty-error" }, [
        node("p", { class: "heading-sm", text: "Could not load the interpretation." }),
        node("p", { text: message }),
      ]),
    );
  }

  function renderCard(data, lane, runDate, spec) {
    const title = node("h2", { class: "heading-sm rail-title", text: titleFor(lane, runDate) });
    const children = [title];
    const meta = metaLine(data.model, data.generated_at, data.duration_ms);
    if (meta) children.push(node("p", { class: "interpretation-meta", text: meta }));
    const bodyEl = node("div", { class: "rail-interp-body" });
    renderInterpretationBody(bodyEl, data, spec);   // shared readable per-section render
    children.push(bodyEl);
    children.push(tuneLink());
    el.replaceChildren(...children);
  }

  async function refresh(state) {
    const token = ++seq;
    if (!state.runDate) {
      renderEmpty(state.lane, "this run");
      return;
    }
    // Show a loading placeholder immediately so a slow fetch never leaves a stale card up.
    renderLoading(state.lane, state.runDate);
    let data, spec;
    try {
      // Window-keyed like the charts; the label/sentinel spec is cached across calls.
      [data, spec] = await Promise.all([
        api.getInterpretation(state.lane, state.startDate, state.endDate),
        loadSpec(),
      ]);
    } catch (err) {
      if (token !== seq) return;                 // superseded: drop the stale failure
      renderError(String(err.message || err));
      return;
    }
    if (token !== seq) return;                    // a newer refresh started: drop this one
    if (!data.text || !data.text.trim()) {
      renderEmpty(state.lane, state.runDate);     // absent row: 200 + empty text
      return;
    }
    renderCard(data, state.lane, state.runDate, spec);
  }

  return { refresh };
}
