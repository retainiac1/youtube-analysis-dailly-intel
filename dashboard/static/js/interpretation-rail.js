// Read-only interpretation rail for the Trends page. Shows the stored LLM summary
// for the current run and lane beside the charts, so the prose and the evidence sit
// together. Display only: it reuses api.getInterpretation (the same data path as the
// dedicated /interpretation page) and has no controls and no write path. The single
// way out is the "Tune" link, which routes to /interpretation for generation.
//
// Interpretations are sparse, so the empty state is the common case and renders
// cleanly (never an error). The endpoint returns 200 with empty text when absent.

import * as api from "./api.js";
import { navigate } from "./router.js";

const INTERPRETATION_ROUTE = "/interpretation";

let el = null;

export function init(mount) {
  el = mount;
}

// Build a DOM node with text assigned via textContent ONLY. The interpretation is
// LLM-generated text, so it is never inserted as HTML (no innerHTML): textContent
// plus CSS white-space: pre-wrap keeps it safe, true prose. Mirrors the per-module
// DOM builder used on the dedicated page (interpretation.js node).
function node(tag, opts = {}, children = []) {
  const n = document.createElement(tag);
  if (opts.class) n.className = opts.class;
  if (opts.text != null) n.textContent = opts.text;
  if (opts.href != null) n.setAttribute("href", opts.href);
  for (const c of children) n.appendChild(c);
  return n;
}

// The "Tune" link. It is created dynamically, so the router does not auto-wire it
// (the router only wires the page-nav links given to initRouter). So intercept the
// plain left-click here and call navigate(); modified and middle clicks fall through
// so cmd/ctrl/middle click still opens /interpretation in a new tab. Keyboard Enter
// fires a plain click, so it activates too.
function tuneLink() {
  const a = node("a", {
    class: "rail-tune",
    href: INTERPRETATION_ROUTE,
    text: "Tune this interpretation",
  });
  a.addEventListener("click", (e) => {
    if (e.defaultPrevented || e.button !== 0 ||
        e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    e.preventDefault();
    navigate(INTERPRETATION_ROUTE);
  });
  return a;
}

// Milliseconds -> "3.2s", or null when un-instrumented. Same shape as
// interpretation.js formatDuration.
function formatDuration(ms) {
  if (ms == null || Number.isNaN(ms)) return null;
  return `${(ms / 1000).toFixed(1)}s`;
}

// Understated "AI-generated, how long, and when" line. generated_at is an Eastern
// ISO-8601 string; show a light, readable form and fall back to the raw value if it
// does not parse. Same shape as interpretation.js metaLine.
function metaLine(model, generatedAt, durationMs) {
  const parts = [];
  if (model) parts.push(`Generated by ${model}`);
  const dur = formatDuration(durationMs);
  if (dur) parts.push(`took ${dur}`);
  if (generatedAt) {
    const d = new Date(generatedAt);
    parts.push(isNaN(d) ? generatedAt : d.toLocaleString());
  }
  return parts.join(" · ");
}

function renderEmpty(lane, runDate) {
  el.replaceChildren(
    node("h2", { class: "heading-sm rail-title", text: titleFor(lane, runDate) }),
    node("div", { class: "rail-empty" }, [
      node("p", { text: "No interpretation generated for this run yet." }),
    ]),
    tuneLink(),
  );
}

function renderError(message) {
  el.replaceChildren(
    node("div", { class: "rail-empty empty-error" }, [
      node("p", { class: "heading-sm", text: "Could not load the interpretation." }),
      node("p", { text: message }),
    ]),
  );
}

// Title names the lane and run so it is clear what the text describes, e.g.
// "Interpretation, health, 2026-06-09".
function titleFor(lane, runDate) {
  return `Interpretation, ${lane}, ${runDate}`;
}

function renderCard(data, lane, runDate) {
  const children = [
    node("h2", { class: "heading-sm rail-title", text: titleFor(lane, runDate) }),
  ];
  const meta = metaLine(data.model, data.generated_at, data.duration_ms);
  if (meta) children.push(node("p", { class: "interpretation-meta", text: meta }));
  children.push(node("div", { class: "interpretation-text", text: data.text }));
  children.push(tuneLink());
  el.replaceChildren(...children);
}

export async function refresh(state) {
  if (!state.runDate) {
    renderEmpty(state.lane, "this run");
    return;
  }
  let data;
  try {
    data = await api.getInterpretation(state.runDate, state.lane);
  } catch (err) {
    renderError(String(err.message || err));
    return;
  }
  // Absent row: endpoint returns 200 with empty text. Treat as empty, not failure.
  if (!data.text || !data.text.trim()) {
    renderEmpty(state.lane, state.runDate);
    return;
  }
  renderCard(data, state.lane, state.runDate);
}
